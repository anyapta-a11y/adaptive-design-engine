"""Синтетический документ-контент для сквозной проверки (вымышленная компания)."""
import sys
from docx import Document
d = Document()
d.add_heading("Итоги пилотного проекта «Северный склад»", 0)
d.add_paragraph("Отчёт для совета директоров, III квартал 2026")
d.add_heading("Что дал проект", 1)
for t in ["Скорость: время комплектации заказа сократилось с 42 до 18 минут.",
          "Точность: доля ошибок при сборке снизилась до 0,4%.",
          "Прозрачность: руководитель видит загрузку смены в реальном времени.",
          "Масштабируемость: решение разворачивается на новом складе за две недели.",
          "Безопасность: число инцидентов с погрузчиками сократилось вдвое."]:
    d.add_paragraph(t, style="List Bullet")
d.add_heading("Ключевые показатели", 1)
for t in ["18 мин: среднее время комплектации", "0,4%: доля ошибок сборки", "2,3 млн ₽: экономия за квартал"]:
    d.add_paragraph(t, style="List Bullet")
d.add_heading("Как проходило внедрение", 1)
for t in ["Аудит процессов", "Пилот на одной смене", "Обучение персонала", "Масштабирование на склад", "Передача в поддержку"]:
    d.add_paragraph(t, style="List Number")
d.add_heading("Результаты по сменам", 1)
rows = [("Смена", "Заказов в день", "Ошибок, %"), ("Утро", "1 240", "0,3"), ("День", "1 410", "0,4"),
        ("Вечер", "1 180", "0,5"), ("Ночь", "620", "0,6"), ("Выходные", "890", "0,4"), ("Праздники", "450", "0,7")]
t = d.add_table(rows=len(rows), cols=3)
for i, r in enumerate(rows):
    for j, v in enumerate(r):
        t.cell(i, j).text = v
d.add_heading("Экономия по направлениям, тыс. ₽", 1)
d.add_paragraph("Персонал — 980; Ошибки и возвраты — 640; Простой техники — 410; Прочее — 270.")
d.add_heading("Выводы и рекомендации", 1)
d.add_paragraph("Пилот подтвердил, что новая система комплектации окупается в течение двух кварталов при текущих объёмах. "
                "Мы рекомендуем распространить решение на склады «Восток» и «Юг» в первом полугодии 2027 года, "
                "сохранив текущую команду внедрения и закрепив за каждым складом ответственного за качество данных. "
                "Отдельно предлагаем пересмотреть нормативы смен с учётом новой скорости комплектации, "
                "поскольку текущие нормативы занижают фактическую производительность примерно на треть.")
d.save(sys.argv[1])
